# Alignment function
def get_X_y_without_nan(X_data, y_df, study_name, target_col="6mo_survival"):
    """
    X_data should be cell scores x samples.
    Returns:
        X_clean: samples x cell scores
        y_clean: numpy array of clinical endpoint
    """

    y_series = y_df.loc[y_df["study"] == study_name, target_col].copy()
    y_series.index = y_series.index.astype(str)

    X_samples = X_data.T.copy()
    X_samples.index = X_samples.index.astype(str)

    common_samples = X_samples.index.intersection(y_series.index)

    print(f"\n{study_name}")
    print("X samples:", X_samples.shape[0])
    print("Metadata labels:", y_series.shape[0])
    print("Common samples:", len(common_samples))

    if len(common_samples) == 0:
        print("No common samples found.")
        print("Example X samples:", list(X_samples.index[:10]))
        print("Example metadata samples:", list(y_series.index[:10]))

    X_aligned = X_samples.loc[common_samples]
    y_aligned = y_series.loc[common_samples]

    # Combine X and y to drop rows where either has NaN
    combined_df = X_aligned.copy()
    combined_df[target_col] = y_aligned

    original_shape = combined_df.shape[0]

    # Convert inf/-inf to NaN before dropping rows
    combined_df.replace([np.inf, -np.inf], np.nan, inplace=True)

    # Drop rows where either X features or y target has NaN values
    # This must happen before converting RECIST to string, otherwise np.nan becomes 'nan' string
    combined_df.dropna(inplace=True)

    # Report if any rows were dropped
    if combined_df.shape[0] < original_shape:
        print(f"Dropped {original_shape - combined_df.shape[0]} samples due to NaN or Inf values in X or y.")

    # Map 'R' to 1 and 'NR' to 0 for 'RECIST' target column
    if target_col == 'RECIST':
        # First, strip whitespace from the target column (now guaranteed not to have np.nan)
        combined_df[target_col] = combined_df[target_col].astype(str).str.strip()
        combined_df[target_col] = combined_df[target_col].replace({'R': 1, 'NR': 0})

    X_clean = combined_df.drop(columns=[target_col])
    y_clean = combined_df[target_col].astype(int).values

    print("After removing NaN labels and features:")
    print("X_clean shape:", X_clean.shape)
    print("y_clean shape:", y_clean.shape)

    if len(y_clean) > 0:
        print("Class counts:")
        print(pd.Series(y_clean).value_counts())

    return X_clean, y_clean


