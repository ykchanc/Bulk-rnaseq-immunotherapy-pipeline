"""## 6. RFE-logistic regression pipeline

### 6.1 Optuna
"""

def objective(trial, X_train_df, y_train_series, inner_cv, scoring, random_state):

    # 1. Penalty, max_iter, class_weight, C
    penalty = trial.suggest_categorical('lr__penalty', ['l1', 'l2', 'elasticnet'])
    max_iter = trial.suggest_categorical('lr__max_iter', [1000])
    # Optuna cannot pass None natively as a categorical string, use a proxy
    class_weight_choice = trial.suggest_categorical('lr__class_weight', ['none', 'balanced'])
    class_weight = None if class_weight_choice == 'none' else 'balanced'
    C = trial.suggest_float('lr__C', 1e-4, 1e4, log=True)


    # 2. Setup hyperparameters of the logistic regression
    l1_ratio = None
    if penalty == 'l1':
        solver = trial.suggest_categorical('lr__solver_l1', ['liblinear', 'saga'])
    elif penalty == 'l2':
        solver = trial.suggest_categorical('lr__solver_l2', ['lbfgs', 'saga'])
    elif penalty == 'elasticnet':
        solver = 'saga'
        l1_ratio = trial.suggest_float('lr__l1_ratio', 0.0, 1.0)

    # Suggested parameters for the final logistic regression model
    lr_params = {
        'C': C,
        'penalty': penalty,
        'solver': solver,
        'max_iter': max_iter,
        'class_weight': class_weight,
        'random_state': random_state
    }
    # Only append l1_ratio if optimizing an elasticnet model
    if l1_ratio is not None:
        lr_params['l1_ratio'] = l1_ratio


    # 3. RFE Hyperparameters
    n_features_to_select = trial.suggest_int('rfe__n_features_to_select', 1, X_train_df.shape[1] // 2)

    # Handle tiny datasets where columns // 10 is 0 (ensure minimum step size of 1)
    max_step = max(1, X_train_df.shape[1] // 10)
    step = trial.suggest_int('rfe__step', 1, max_step)

    # Hyperparameters for the logistic regression estimator *within* RFE
    rfe_estimator_C = trial.suggest_float('rfe_estimator__C', 1e-3, 10.0, log=True)

    # Use a stable configuration for the RFE ranking
    current_rfe_estimator = LogisticRegression(
        random_state=random_state,
        solver='liblinear',
        C=rfe_estimator_C,
        class_weight=class_weight # Apply class_weight
    )

    current_rfe = RFE(
        estimator=current_rfe_estimator,
        n_features_to_select=n_features_to_select,
        step=step
    )

    current_lr_model = LogisticRegression(**lr_params)

    cv_scores = []
    fold_selected_features = []
    feature_names = np.array(X_train_df.columns)

    # Cross-validation loops
    for train_inner_idx, val_inner_idx in inner_cv.split(X_train_df, y_train_series):
        X_train_inner_fold, X_val_inner_fold = X_train_df.iloc[train_inner_idx], X_train_df.iloc[val_inner_idx]
        y_train_inner_fold, y_val_inner_fold = y_train_series.iloc[train_inner_idx], y_train_series.iloc[val_inner_idx]

        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            current_rfe.fit(X_train_inner_fold, y_train_inner_fold)
        selected_mask = current_rfe.get_support()

        if not selected_mask.any():
            current_n_features_to_select_trial = trial.params.get('rfe__n_features_to_select')
            warnings.warn(f"Trial {trial.number} - Fold: RFE selected 0 features. Optuna's 'n_features_to_select' was {current_n_features_to_select_trial}. Returning -np.inf.")
            return -np.inf

        X_train_transformed = X_train_inner_fold.loc[:, selected_mask]
        X_val_transformed = X_val_inner_fold.loc[:, selected_mask]

        selected_in_fold = feature_names[selected_mask]
        fold_selected_features.append(list(selected_in_fold))

        lr_fold_model = clone(current_lr_model)
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            lr_fold_model.fit(X_train_transformed, y_train_inner_fold)

        if scoring == 'roc_auc':
            y_pred_proba = lr_fold_model.predict_proba(X_val_transformed)[:, 1]
            score = roc_auc_score(y_val_inner_fold.astype(int), y_pred_proba)
        else:
            y_pred = lr_fold_model.predict(X_val_transformed)
            score = accuracy_score(y_val_inner_fold.astype(int), y_pred)

        cv_scores.append(score)

    if not cv_scores:
        return -np.inf

    trial_union_features = list(set([feat for fold in fold_selected_features for feat in fold]))
    trial.set_user_attr("union_features", trial_union_features)

    return np.mean(cv_scores)

"""### 6.2. RFE-Logreg Pipeline Function"""

def run_lr_rfe_external_cv(
    datasets,
    inner_cv_type='3fold',
    scoring='roc_auc',
    random_state=42,
    n_trials=50
):
    outer_results = []
    n_datasets = len(datasets)

    for test_idx in range(n_datasets):
        print(f"\nExternal test dataset: Dataset {test_idx + 1}")
        print("—" * 50)

        train_sets = [datasets[i] for i in range(n_datasets) if i != test_idx]

        feature_names_orig = datasets[0][0].columns.tolist()

        X_train = np.vstack([d[0].to_numpy() for d in train_sets])
        y_train = np.concatenate([np.asarray(d[1]) for d in train_sets])

        X_test, y_test = datasets[test_idx]
        X_test = X_test.to_numpy()
        y_test = np.asarray(y_test)

        print(f"Training set shape (n-1 global pool): {X_train.shape}")
        print(f"Test set shape (n=1 hold-out evaluation dataset): {X_test.shape}")

        if inner_cv_type == '2fold':
            inner_cv = StratifiedKFold(n_splits=2, shuffle=True, random_state=random_state)
        elif inner_cv_type == '3fold':
            inner_cv = StratifiedKFold(n_splits=3, shuffle=True, random_state=random_state)
        elif inner_cv_type == '5fold':
            inner_cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=random_state)
        elif inner_cv_type == 'loocv':
            inner_cv = LeaveOneOut()
        else:
            raise ValueError("inner_cv_type must be '2fold', '3fold', '5fold', or 'loocv'")

        X_train_df = pd.DataFrame(X_train, columns=feature_names_orig)
        y_train_series = pd.Series(y_train)
        X_test_df = pd.DataFrame(X_test, columns=feature_names_orig)

        for name, df in [("X_train_df", X_train_df), ("X_test_df", X_test_df)]:
            nans = df.isna().sum().sum()
            infs = np.isinf(df.to_numpy()).sum()
            if nans > 0 or infs > 0:
                raise ValueError(f"NaNs/Infs detected in {name}: NaNs={nans}, Infs={infs}")

        if np.isnan(y_train_series).any() or np.isinf(y_train_series).any():
            raise ValueError("NaNs or Infs detected in y_train_series.")

        print(f"\nExecuting Optuna optimization for {n_trials} trials across internal {inner_cv_type} loops...")

        optuna.logging.set_verbosity(optuna.logging.WARNING)
        study = optuna.create_study(direction='maximize', sampler=optuna.samplers.TPESampler(seed=random_state))

        func = lambda trial: objective(trial, X_train_df, y_train_series, inner_cv, scoring, random_state)
        study.optimize(func, n_trials=n_trials)

        best_trial = study.best_trial
        best_pipeline_params = best_trial.params
        best_inner_cv_score = best_trial.value

        best_rfe_params = {k.replace('rfe__', ''): v for k, v in best_pipeline_params.items() if k.startswith('rfe__')}

        # Reconstruct best_lr_params to use a single 'solver' key
        best_lr_params = {
            k.replace('lr__', ''): v for k, v in best_pipeline_params.items()
            if k.startswith('lr__') and not k.startswith('lr__solver_')
        }

        # Determine the correct solver based on the chosen penalty
        penalty = best_lr_params.get('penalty')
        if penalty == 'l1':
            best_lr_params['solver'] = best_pipeline_params['lr__solver_l1']
        elif penalty == 'l2':
            best_lr_params['solver'] = best_pipeline_params['lr__solver_l2']
        elif penalty == 'elasticnet':
            best_lr_params['solver'] = 'saga' # Elasticnet solver is fixed to 'saga'

        # Add random_state which is a constant for logistic regression
        best_lr_params['random_state'] = random_state

        # Convert 'none' string for class_weight to None object
        if best_lr_params.get('class_weight') == 'none':
            best_lr_params['class_weight'] = None

        # Get C for RFE estimator
        best_rfe_estimator_C = best_pipeline_params.get('rfe_estimator__C', 1.0)

        union_selected_features = best_trial.user_attrs.get("union_features", feature_names_orig)
        n_selected_features = len(union_selected_features)

        print(f"\nFeature selection complete via Internal CV Fold Union.")
        print(f"Retained {n_selected_features} out of {len(feature_names_orig)} features.")

        X_train_final = X_train_df[union_selected_features]
        X_test_final = X_test_df[union_selected_features]

        print("Retraining final Logistic Regression model on filtered n-1 training data...")

        final_pipeline = Pipeline([
            ('rfe', RFE(estimator=LogisticRegression(random_state=random_state, solver='liblinear',
                                                      C=best_rfe_estimator_C),
                                                      n_features_to_select=best_rfe_params.get('n_features_to_select'),
                                                      step=best_rfe_params.get('step'))),
            ('lr', LogisticRegression(**best_lr_params))
        ])

        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            final_pipeline.fit(X_train_final, y_train_series)

        print("Evaluating final model on isolated held-out dataset...")

        y_pred = final_pipeline.predict(X_test_final)

        is_binary = len(np.unique(y_train)) == 2
        f1_avg = 'binary' if is_binary else 'macro'

        accuracy = accuracy_score(y_test, y_pred)
        balanced_acc = balanced_accuracy_score(y_test, y_pred)
        f1 = f1_score(y_test, y_pred, average=f1_avg)

        external_auc = None
        y_prob = None

        if is_binary:
            try:
                y_prob = final_pipeline.predict_proba(X_test_final)[:, 1]
                external_auc = roc_auc_score(y_test, y_prob)
            except Exception as e:
                print(f"Warning: Could not compute external AUC: {e}")

        result = {
            'held_out_dataset': test_idx + 1,
            'inner_cv_type': inner_cv_type,
            'best_params': best_pipeline_params,
            'best_inner_cv_score': best_inner_cv_score,
            'selected_features_list': union_selected_features,
            'n_features_used': n_selected_features,
            'external_accuracy': accuracy,
            'external_balanced_accuracy': balanced_acc,
            'external_f1': f1,
            'external_auc': external_auc,
            'confusion_matrix': confusion_matrix(y_test, y_pred),
            'y_test': y_test,
            'y_pred': y_pred,
            'y_prob': y_prob
        }
        outer_results.append(result)

    return outer_results

