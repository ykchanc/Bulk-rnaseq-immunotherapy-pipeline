def make_json_safe(obj):
    """
    Convert NumPy/scikit-learn objects into JSON-safe Python objects.
    """

    if isinstance(obj, np.ndarray):
        return obj.tolist()

    if isinstance(obj, np.integer):
        return int(obj)

    if isinstance(obj, np.floating):
        if np.isnan(obj):
            return None
        return float(obj)

    if isinstance(obj, np.bool_):
        return bool(obj)

    if isinstance(obj, float):
        if np.isnan(obj):
            return None
        return obj

    if isinstance(obj, tuple):
        return [make_json_safe(x) for x in obj]

    if isinstance(obj, list):
        return [make_json_safe(x) for x in obj]

    if isinstance(obj, dict):
        return {str(k): make_json_safe(v) for k, v in obj.items()}

    return obj



# 2. The results_to_dataframe function
def results_to_dataframe(
    results,
    save=False,
    path_folder="/content/drive/MyDrive/M13_FYP/20261018_codes_to_submit/",
    prefix="rfe_logreg_results"
):
    rows = []

    for r in results:

        # -------------------------------
        # 1. Confusion matrix
        # -------------------------------
        conf_mat = r.get("confusion_matrix")
        conf_mat = make_json_safe(conf_mat)

        # -------------------------------
        # 2. Best parameters
        # -------------------------------
        best_params = r.get("best_params")
        best_params = make_json_safe(best_params)

        # -------------------------------
        # 3. Add rows to the dataframe
        # -------------------------------
        rows.append({
            "held_out_dataset": r.get("held_out_dataset"),
            "inner_cv_type": r.get("inner_cv_type"),
            "best_inner_cv_score": make_json_safe(r.get("best_inner_cv_score")),

            "external_accuracy": make_json_safe(r.get("external_accuracy")),
            "external_balanced_accuracy": make_json_safe(r.get("external_balanced_accuracy")),
            "external_f1": make_json_safe(r.get("external_f1")),
            "external_auc": make_json_safe(r.get("external_auc")),

            "n_features_used": make_json_safe(r.get("n_features_used")),

            "confusion_matrix": conf_mat,
            "best_params": best_params
        })

    df_results = pd.DataFrame(rows)

    # -------------------------------
    # 4. Save outputs
    # -------------------------------
    if save:
        os.makedirs(path_folder, exist_ok=True)
        csv_path = os.path.join(path_folder, f"{prefix}.csv")
        pkl_path = os.path.join(path_folder, f"{prefix}_full.pkl")
        excel_path = os.path.join(path_folder, f"{prefix}.xlsx")

        df_csv = df_results.copy()

        json_cols = [
            "best_params",
            "confusion_matrix"
        ]

        for col in json_cols:
            if col in df_csv.columns:
                df_csv[col] = df_csv[col].apply(
                    lambda x: json.dumps(make_json_safe(x)) if x is not None else None
                )

        df_csv.to_csv(csv_path, index=False)
        df_csv.to_excel(excel_path, index=False)

        # Save full results object as pickle
        with open(pkl_path, "wb") as f:
            pickle.dump(results, f)

        print(f"\n[INFO] Saved summary CSV to: {csv_path}")
        print(f"[INFO] Saved summary Excel to: {excel_path}")
        print(f"[INFO] Saved full results pickle to: {pkl_path}")

    return df_results



# 3. The generate_and_save_roc_curves function
def generate_and_save_roc_curves(results, output_dir, prefix="model_setting"):
    """
    Generates, displays, and saves an ROC Curve plot from cross-validation results,
    including individual, micro-average, and macro-average curves/scores with standard deviation shading.
    """
    os.makedirs(output_dir, exist_ok=True)

    plt.figure(figsize=(9, 7)) # Figure size
    valid_curves = 0
    all_y_test_micro = []
    all_y_prob_micro = []

    tprs = []
    base_fpr = np.linspace(0, 1, 101) # FPR points space for curves interpolation

    for r in results:
        y_test = np.array(r.get('y_test')) if r.get('y_test') is not None else None
        y_prob = np.array(r.get('y_prob')) if r.get('y_prob') is not None else None
        dataset_num = r.get('held_out_dataset', '?')

        if y_prob is not None and y_test is not None and len(np.unique(y_test)) == 2:
            fpr, tpr, _ = roc_curve(y_test, y_prob)
            roc_auc = auc(fpr, tpr)
            valid_curves += 1

            plt.plot(
                fpr,
                tpr,
                linewidth=1.5,
                label=f"Dataset {dataset_num} (AUC = {roc_auc:.3f})"
            )
            all_y_test_micro.append(y_test)
            all_y_prob_micro.append(y_prob)

            # For Macro-average ROC curve
            tpr_interpolated = np.interp(base_fpr, fpr, tpr)
            tpr_interpolated[0] = 0.0 # Ensure it starts at 0,0 (macroAUC)
            tprs.append(tpr_interpolated)

    if valid_curves == 0:
        print(f"[WARNING] No binary targets with valid probabilities found for prefix: '{prefix}'. Skipping ROC plot.")
        plt.close()
        return

    # Micro-average ROC Curve
    if all_y_test_micro and all_y_prob_micro:
        y_true_micro = np.concatenate(all_y_test_micro)
        y_score_micro = np.concatenate(all_y_prob_micro)

        fpr_micro, tpr_micro, _ = roc_curve(y_true_micro, y_score_micro)
        roc_auc_micro = auc(fpr_micro, tpr_micro)
        plt.plot(
            fpr_micro, tpr_micro, label=f'Micro-average (AUC = {roc_auc_micro:.3f})',
            color='deeppink', linestyle=':', linewidth=3
        )

    # Macro-average ROC Curve and standard deviation
    if tprs:
        mean_tprs = np.mean(tprs, axis=0)
        mean_tprs[-1] = 1.0 # Ensure it ends at 1,1
        macro_roc_auc = auc(base_fpr, mean_tprs)

        # Calculate standard deviation
        std_tprs = np.std(tprs, axis=0)
        tprs_upper = np.minimum(mean_tprs + std_tprs, 1) # Stop at 1
        tprs_lower = np.maximum(mean_tprs - std_tprs, 0) # Stop at 0

        plt.plot(
            base_fpr, mean_tprs, label=f'Macro-average (AUC = {macro_roc_auc:.3f})',
            color='navy', linestyle='--', linewidth=3
        )
        plt.fill_between(base_fpr, tprs_lower, tprs_upper, color='blue', alpha=0.1,
                         label=f'Macro-average \u00B1 1 SD')

    plt.plot([0, 1], [0, 1], linestyle='--', color='gray', alpha=0.7)
    plt.xlim([-0.02, 1.02])
    plt.ylim([-0.02, 1.02])
    plt.xlabel('False Positive Rate')
    plt.ylabel('True Positive Rate')
    plt.title(f'ROC Curves for External Held-out Datasets\n({prefix})')
    plt.legend(loc='lower right')
    plt.grid(True, linestyle='--', alpha=0.7) # Changed grid style for better contrast
    plt.tight_layout()

    # Save image file
    save_filename = f"{prefix}_roc_curves.png"
    save_path = os.path.join(output_dir, save_filename)
    plt.savefig(save_path, dpi=300, bbox_inches='tight')
    print(f"[SUCCESS] ROC Curves plot saved to: {save_path}")

    # Display in notebook
    plt.show()



# 4. The generate_and_save_f1_scores function
def generate_and_save_f1_scores(results, output_dir, prefix="model_setting"):
    """
    Generates, displays, and saves an F1 Score comparison bar chart.
    """
    os.makedirs(output_dir, exist_ok=True)

    # Extract keys safely
    datasets_labels = [f"Dataset {r.get('held_out_dataset', '?')}" for r in results]
    f1_scores = [r.get('external_f1', 0.0) for r in results]
    mean_f1 = np.mean(f1_scores) if f1_scores else 0

    plt.figure(figsize=(8, 5))

    # Render chart elements
    bars = plt.bar(datasets_labels, f1_scores, color='skyblue', edgecolor='navy', alpha=0.8, width=0.6)
    plt.axhline(mean_f1, color='red', linestyle='--', linewidth=1.5, label=f'Mean F1 ({mean_f1:.3f})')

    # Add labels on top of individual bars
    for bar in bars:
        height = bar.get_height()
        plt.text(
            bar.get_x() + bar.get_width()/2.0,
            height + 0.01,
            f"{height:.3f}",
            ha='center',
            va='bottom',
            fontsize=10,
            fontweight='bold'
        )

    plt.ylim([0, 1.1])
    plt.ylabel('F1 Score')
    plt.title(f'External F1 Score across Cross-Validation Splits\n({prefix})')
    plt.grid(axis='y', linestyle=':', alpha=0.6)
    plt.legend(loc='upper right')
    plt.tight_layout()

    # Save image file
    save_filename = f"{prefix}_f1_scores.png"
    save_path = os.path.join(output_dir, save_filename)
    plt.savefig(save_path, dpi=300, bbox_inches='tight')
    print(f"[SUCCESS] F1 Scores plot saved to: {save_path}")

    # Display in notebook
    plt.show()

