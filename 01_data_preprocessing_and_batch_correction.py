"""## 6. Convert Cui2021 from FPKM to TPM

Since data in all other datasets are expressed in **log2(TPM+1)** , thus converting the Cui2021 dataset from **log2(FPKM+1)** to **log2(TPM+1)** is needed.
"""

import numpy as np
import pandas as pd

# Ensure DataFrame with genes as rows and samples as columns
# The values inside df are log2(FPKM + 1)
df_Cui2021_raw = dfs['df_Cui2021_raw']

# 1. Reverse log transformation from log2(FPKM + 1) back to linear FPKM
cui_fpkm_data = 2**df_Cui2021_raw - 1

# 2. Correct negative values caused by floating-point rounding errors
cui_fpkm_data = cui_fpkm_data.clip(lower=0)

# 3. Calculate column sums (total FPKM per sample)
fpkm_sums = cui_fpkm_data.sum(axis=0)

# 4. Convert FPKM to TPM (divide each sample by its sum and multiply by 1M)
# Use .div() to divide across columns and handle cases where sum might be 0
tpm_data = cui_fpkm_data.div(fpkm_sums, axis=1).fillna(0) * 1e6

# 5. Transform back to log2(TPM + 1)
df_Cui2021_TPM = np.log2(tpm_data + 1)

