# 2. Helper function for saving and plotting
def process_and_plot_embeddings(data_matrix, meta_df, title_prefix, filename):
    """Computes PCA, t-SNE, and UMAP embeddings for gene expression matrix,

    saves the output plot to the specified folder, and displays it.
    """
    # Align metadata with the current matrix columns (samples)
    meta_df_aligned = meta_df.loc[data_matrix.columns].copy()
    assert meta_df_aligned.index.equals(
        data_matrix.columns
    ), f"Error: Alignment failed for {title_prefix}!"

    # Dimensionality Reduction (Samples as rows, features as columns)
    X = data_matrix.T
    X_scaled = StandardScaler().fit_transform(X)

    # Compute PCA
    pca = PCA(n_components=2, random_state=42)
    X_pca = pca.fit_transform(X_scaled)
    meta_df_aligned["PCA1"] = X_pca[:, 0]
    meta_df_aligned["PCA2"] = X_pca[:, 1]

    # Compute t-SNE
    tsne = TSNE(n_components=2, perplexity=30, random_state=42, n_iter=1000)
    X_tsne = tsne.fit_transform(X_scaled)
    meta_df_aligned["tSNE1"] = X_tsne[:, 0]
    meta_df_aligned["tSNE2"] = X_tsne[:, 1]

    # Compute UMAP
    reducer = umap.UMAP(n_components=2, random_state=42, n_neighbors=15)
    X_umap = reducer.fit_transform(X_scaled)
    meta_df_aligned["UMAP1"] = X_umap[:, 0]
    meta_df_aligned["UMAP2"] = X_umap[:, 1]

    # Plotting grid layout
    grouping_cols = ["study", "RECIST", "1year_survival", "6mo_survival"]
    methods = [
        ("PCA1", "PCA2", "PCA"),
        ("tSNE1", "tSNE2", "t-SNE"),
        ("UMAP1", "UMAP2", "UMAP"),
    ]

    fig, axes = plt.subplots(4, 3, figsize=(18, 20))
    fig.suptitle(
        f"Dimensionality Reduction - {title_prefix}",
        fontsize=18,
        fontweight="bold",
        y=1.02,
    )
    plt.subplots_adjust(hspace=0.4, wspace=0.3)

    for row_idx, group in enumerate(grouping_cols):
        if group not in meta_df_aligned.columns:
            print(
                f"Warning: {group} column missing from metadata in {title_prefix}. Skipping row."
            )
            continue

        for col_idx, (x_dim, y_dim, method_name) in enumerate(methods):
            ax = axes[row_idx, col_idx]

            sns.scatterplot(
                data=meta_df_aligned,
                x=x_dim,
                y=y_dim,
                hue=group,
                palette="Set2",
                alpha=0.8,
                ax=ax,
            )

            ax.set_title(
                f"{method_name} grouped by {group} ({title_prefix})",
                fontsize=11,
            )
            ax.set_xlabel(x_dim)
            ax.set_ylabel(y_dim)
            ax.legend(title=group, bbox_to_anchor=(1.02, 1), loc="upper left")

    plt.tight_layout()

    # Save directly to the specified fold
    full_save_path = os.path.join(OUTPUT_DIR, filename)
    plt.savefig(full_save_path, dpi=300, bbox_inches="tight")
    print(f"Saved plot successfully: {full_save_path}")

    # Render on screen and close cache
    plt.show()
    plt.close(fig)

