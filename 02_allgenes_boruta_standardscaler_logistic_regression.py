# 3. PIPELINE EXECUTION ENGINE
def run_boruta_logistic_regression_external_cv(
    datasets,
    inner_cv_type='5fold',
    scoring='balanced_accuracy',
    random_state=42
):
    outer_results = []
    n_datasets = len(datasets)

    for test_idx in range(n_datasets):
        print(f"\nExternal test dataset: Dataset {test_idx + 1}")
        print("-" * 50)

        # External expression data combining
        train_sets = [datasets[i] for i in range(n_datasets) if i != test_idx]
        X_train = np.vstack([d[0] for d in train_sets])
        y_train = np.concatenate([d[1] for d in train_sets])
        X_test, y_test = datasets[test_idx]

        print(f"Training set shape (Pre-Boruta): {X_train.shape}")
        print(f"Test set shape (Pre-Boruta): {X_test.shape}")

        # Run Boruta
        print("Running Boruta Feature Selection...")
        boruta_selector = BorutaFeatureSelector(n_estimators=50, random_state=random_state)
        X_train_selected = boruta_selector.fit_transform(X_train, y_train)
        X_test_selected = boruta_selector.transform(X_test)

        selected_features_mask = boruta_selector.support_
        selected_feature_indices = np.where(selected_features_mask)[0]
        n_selected_features = selected_features_mask.sum()
        print(f"Boruta Step Completed. Selected Features: {n_selected_features}")

        # Determine internal CV strategy
        if inner_cv_type == '10fold':
            inner_cv = StratifiedKFold(n_splits=10, shuffle=True, random_state=random_state)
        elif inner_cv_type == '5fold':
            inner_cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=random_state)
        elif inner_cv_type == 'loocv':
            inner_cv = LeaveOneOut()
        else:
            raise ValueError("inner_cv_type must be '10fold', '5fold', or 'loocv'")

        # Internal Pipeline (No Boruta inside, to save computing resource)
        # If Boruta is put inside the pipeline, runtime would exceed 24 hours.
        pipe = Pipeline([
            ('scaler', StandardScaler()),
            ('logreg', LogisticRegression(max_iter=5000, random_state=random_state))
        ])

        print("\nStarting GridSearchCV on optimized features...")
        grid = GridSearchCV(
            estimator=pipe,
            param_grid=param_grid,
            cv=inner_cv,
            scoring=scoring,
            n_jobs=-1,
            refit=True,
            verbose=1
        )

        try:
            grid.fit(X_train_selected, y_train)
        except Exception as e:
            print(f"Error during GridSearchCV with n_jobs=-1: {e}. Retrying with n_jobs=1...")
            grid.n_jobs = 1
            grid.fit(X_train_selected, y_train)

        best_model = grid.best_estimator_

        # Prediction on held-out dataset
        y_pred = best_model.predict(X_test_selected)

        # Metrics calculations
        is_binary = len(np.unique(y_train)) == 2
        f1_avg = 'binary' if is_binary else 'macro'

        accuracy = accuracy_score(y_test, y_pred)
        balanced_acc = balanced_accuracy_score(y_test, y_pred)
        f1 = f1_score(y_test, y_pred, average=f1_avg)

        auc = None
        y_prob = None
        if is_binary:
            try:
                y_prob = best_model.predict_proba(X_test_selected)[:, 1]
                auc = roc_auc_score(y_test, y_prob)
            except Exception as e:
                print(f"Warning: Could not compute AUC: {e}")

        result = {
            'held_out_dataset': test_idx + 1,
            'inner_cv_type': inner_cv_type,
            'best_params': grid.best_params_,
            'best_inner_cv_score': grid.best_score_,
            'external_accuracy': accuracy,
            'external_balanced_accuracy': balanced_acc,
            'external_f1': f1,
            'external_auc': auc,
            'confusion_matrix': confusion_matrix(y_test, y_pred),
            'y_test': y_test,
            'y_pred': y_pred,
            'y_prob': y_prob,
            'selected_features_mask': selected_features_mask,
            'selected_feature_indices': selected_feature_indices,
            'n_selected_features': n_selected_features,
            'boruta_ranking': boruta_selector.ranking_
        }
        outer_results.append(result)

        print("\n" + "=" * 50)
        print(f"RESULTS FOR DATASET {test_idx + 1}:")
        print("=" * 50)
        print(f"Best Parameters: {grid.best_params_}")
        print(f"Best Internal CV Score: {grid.best_score_:.4f}")
        print(f"External Accuracy: {accuracy:.4f} | Balanced Acc: {balanced_acc:.4f} | F1 ({f1_avg}): {f1:.4f}")
        print(f"External AUC: {f'{auc:.4f}' if auc is not None else 'N/A'}")
        print(f"Number of selected features: {n_selected_features}")
        print("\nClassification report:")
        print(classification_report(y_test, y_pred))

    return outer_results

