# 4. DATA EXPORTATION HANDLER
def results_to_dataframe(results, save=False, output_dir=None, prefix="boruta_logreg_results"):
    rows = []
    for r in results:
        selected_indices = r.get("selected_feature_indices")
        if isinstance(selected_indices, np.ndarray):
            selected_indices = selected_indices.tolist()

        boruta_ranking = r.get("boruta_ranking")
        if isinstance(boruta_ranking, np.ndarray):
            boruta_ranking = boruta_ranking.tolist()

        conf_mat = r.get("confusion_matrix")
        if isinstance(conf_mat, np.ndarray):
            conf_mat = conf_mat.tolist()

        rows.append({
            "held_out_dataset": r.get("held_out_dataset"),
            "inner_cv_type": r.get("inner_cv_type"),
            "best_inner_cv_score": r.get("best_inner_cv_score"),
            "external_accuracy": r.get("external_accuracy"),
            "external_balanced_accuracy": r.get("external_balanced_accuracy"),
            "external_f1": r.get("external_f1"),
            "external_auc": r.get("external_auc"),
            "n_selected_features": r.get("n_selected_features"),
            "selected_feature_indices": selected_indices,
            "boruta_ranking": boruta_ranking,
            "confusion_matrix": conf_mat,
            "best_params": r.get("best_params")
        })

    df_results = pd.DataFrame(rows)

    if save:
        if output_dir is None:
            output_dir = "."
        os.makedirs(output_dir, exist_ok=True)

        csv_path = os.path.join(output_dir, f"{prefix}.csv")
        pkl_path = os.path.join(output_dir, f"{prefix}_full.pkl")

        df_csv = df_results.copy()
        for col in ["best_params", "selected_feature_indices", "boruta_ranking", "confusion_matrix"]:
            if col in df_csv.columns:
                df_csv[col] = df_csv[col].apply(lambda x: json.dumps(x) if x is not None else None)

        df_csv.to_csv(csv_path, index=False)
        with open(pkl_path, "wb") as f:
            pickle.dump(results, f)

        print(f"\n[INFO] Saved summary CSV to: {csv_path}")
        print(f"[INFO] Saved full results pickle to: {pkl_path}")

    return df_results

