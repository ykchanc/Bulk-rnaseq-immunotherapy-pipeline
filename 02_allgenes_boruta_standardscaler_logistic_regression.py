# 1. BORUTA SELECTOR
class BorutaFeatureSelector(BaseEstimator, TransformerMixin):
    def __init__(self, max_iter=50, perc=90, n_estimators=50, random_state=None):
        self.max_iter = max_iter
        self.perc = perc
        self.n_estimators = n_estimators
        self.random_state = random_state

    def fit(self, X, y):
        if hasattr(X, "columns"):
            self.feature_names_in_ = np.array(X.columns)
        else:
            self.feature_names_in_ = np.array([f"x{i}" for i in range(X.shape[1])])

        rf = RandomForestClassifier(
            n_estimators=self.n_estimators,
            n_jobs=1,
            random_state=self.random_state,
            class_weight="balanced"
        )

        self.boruta_ = BorutaPy(
            estimator=rf,
            max_iter=self.max_iter,
            perc=self.perc,
            verbose=0,
            random_state=self.random_state
        )

        X_array = X.to_numpy() if hasattr(X, "to_numpy") else np.asarray(X)
        y_array = y.to_numpy() if hasattr(y, "to_numpy") else np.asarray(y)

        self.boruta_.fit(X_array, y_array)

        self.support_ = self.boruta_.support_.copy()
        self.ranking_ = self.boruta_.ranking_
        self.support_weak_ = self.boruta_.support_weak_

        if self.support_.sum() == 0:
            warnings.warn("Boruta selected zero confirmed features. Using tentative features instead.", UserWarning)
            self.support_ = self.support_weak_.copy()

        if self.support_.sum() == 0:
            warnings.warn("Boruta selected no confirmed or tentative features. Using best-ranked feature.", UserWarning)
            self.support_ = np.zeros_like(self.boruta_.support_, dtype=bool)
            self.support_[np.argmin(self.boruta_.ranking_)] = True

        self.support_mask_ = self.support_
        self.selected_feature_names_ = self.feature_names_in_[self.support_]

        return self

    def transform(self, X):
        X_array = X.to_numpy() if hasattr(X, "to_numpy") else np.asarray(X)
        return X_array[:, self.support_]

    def get_feature_names_out(self, input_features=None):
        return self.feature_names_in_[self.support_]

