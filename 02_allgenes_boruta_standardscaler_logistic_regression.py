def get_X_y_without_nan(X, y_df, study_name, target_col="2mo_survival"):
    # Filter the target dataframe for the selected study as a Pandas Series
    y_series = y_df.loc[y_df["study"] == study_name, target_col]

    # Modification: Handing mapping for RECIST (Assuming no 'NE' values exist)
    if target_col == "RECIST":
        # Clean white spaces and standardize text for mapping
        y_str = y_series.astype(str).str.strip().str.upper()

        # Initialize an empty series to hold our numerical mappings
        mapped_y = pd.Series(index=y_series.index, dtype=float)

        # Map 'NR' (Non-Responder) to 1 first
        mapped_y[y_str.str.contains("NR", na=False)] = 1
        # Map 'R' (Responder) to 0, ensuring we don't overwrite the 'NR' entries
        mapped_y[y_str.str.contains("R", na=False) & ~y_str.str.contains("NR", na=False)] = 0

        # Update our working series
        y_series = mapped_y

    # Robust boolean mask: pd.notna safely handles mixed types, strings, None, and NaNs
    mask = pd.notna(y_series).values

    # Extract target array and subset it safely
    y_clean = y_series.values[mask].astype(int)

    # Subset features matrix (transposing X based on the clean indices)
    X_clean = X.T[mask]

    return X_clean, y_clean

