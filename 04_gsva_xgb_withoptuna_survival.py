# 3. The generate_and_save_roc_curves function
def generate_and_save_roc_curves(results, output_dir, prefix="model_setting"):
    """
    Generates, displays, and saves an ROC Curve plot from cross-validation results,
    including individual, micro-average, and macro-average curves/scores with standard deviation shading.
    """
    os.makedirs(output_dir, exist_ok=True)

    plt.figure(figsize=(9, 7)) # Figure size
    valid_curves = 0
    all_y_test_micro = []
    all_y_prob_micro = []

    tprs = []
    base_fpr = np.linspace(0, 1, 101) # FPR points space for curves interpolation

    for r in results:
        y_test = np.array(r.get('y_test')) if r.get('y_test') is not None else None
        y_prob = np.array(r.get('y_prob')) if r.get('y_prob') is not None else None
        dataset_num = r.get('held_out_dataset', '?')

        if y_prob is not None and y_test is not None and len(np.unique(y_test)) == 2:
            fpr, tpr, _ = roc_curve(y_test, y_prob)
            roc_auc = auc(fpr, tpr)
            valid_curves += 1

            plt.plot(
                fpr,
                tpr,
                linewidth=1.5,
                label=f"Dataset {dataset_num} (AUC = {roc_auc:.3f})"
            )
            all_y_test_micro.append(y_test)
            all_y_prob_micro.append(y_prob)

            # For ROC curves
            tpr_interpolated = np.interp(base_fpr, fpr, tpr)
            tpr_interpolated[0] = 0.0 # Ensure it starts at 0,0 (macroAUC)
            tprs.append(tpr_interpolated)

    if valid_curves == 0:
        print(f"[WARNING] No binary targets with valid probabilities found for prefix: '{prefix}'. Skipping ROC plot.")
        plt.close()
        return

    # Micro-average ROC Curve
    if all_y_test_micro and all_y_prob_micro:
        y_true_micro = np.concatenate(all_y_test_micro)
        y_score_micro = np.concatenate(all_y_prob_micro)

        fpr_micro, tpr_micro, _ = roc_curve(y_true_micro, y_score_micro)
        roc_auc_micro = auc(fpr_micro, tpr_micro)
        plt.plot(
            fpr_micro, tpr_micro, label=f'Micro-average (AUC = {roc_auc_micro:.3f})',
            color='deeppink', linestyle=':', linewidth=3
        )

    # Macro-average ROC Curve and standard deviation
    if tprs:
        mean_tprs = np.mean(tprs, axis=0)
        mean_tprs[-1] = 1.0 # Ensure it ends at 1,1
        macro_roc_auc = auc(base_fpr, mean_tprs)

        # Calculate standard deviation
        std_tprs = np.std(tprs, axis=0)
        tprs_upper = np.minimum(mean_tprs + std_tprs, 1) # Stop at 1
        tprs_lower = np.maximum(mean_tprs - std_tprs, 0) # Stop at 0

        plt.plot(
            base_fpr, mean_tprs, label=f'Macro-average (AUC = {macro_roc_auc:.3f})',
            color='navy', linestyle='--', linewidth=3
        )
        plt.fill_between(base_fpr, tprs_lower, tprs_upper, color='blue', alpha=0.1,
                         label=f'Macro-average \u00B1 1 SD')

    plt.plot([0, 1], [0, 1], linestyle='--', color='gray', alpha=0.7)
    plt.xlim([-0.02, 1.02])
    plt.ylim([-0.02, 1.02])
    plt.xlabel('False Positive Rate')
    plt.ylabel('True Positive Rate')
    plt.title(f'ROC Curves for External Held-out Datasets\n({prefix})')
    plt.legend(loc='lower right')
    plt.grid(True, linestyle='--', alpha=0.7) # Can change grid style for better contrast
    plt.tight_layout()

    # Save image file
    save_filename = f"{prefix}_roc_curves.png"
    save_path = os.path.join(output_dir, save_filename)
    plt.savefig(save_path, dpi=300, bbox_inches='tight')
    print(f"[SUCCESS] ROC Curves plot saved to: {save_path}")

    # Display in notebook
    plt.show()



