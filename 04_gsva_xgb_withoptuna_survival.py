def objective(trial, X_train_df, y_train_series, inner_cv, scoring, random_state):
    xgb_params = {
        'scale_pos_weight': trial.suggest_float('xgb__scale_pos_weight', 1.0, 15.0),
        'n_estimators': trial.suggest_int('xgb__n_estimators', 50, 150, step=50),
        'max_depth': trial.suggest_int('xgb__max_depth', 3, 8),
        'max_leaves': trial.suggest_int('xgb__max_leaves', 3, 5, step=1),
        'grow_policy': 'lossguide',
        'learning_rate': trial.suggest_float('xgb__learning_rate', 0.001, 0.3, log=True),
        'subsample': trial.suggest_float('xgb__subsample', 0.4, 1.0),
        'colsample_bytree': trial.suggest_float('xgb__colsample_bytree', 0.2, 0.8, step=0.1),
        'gamma': trial.suggest_float('xgb__gamma', 1e-5, 5.0, log=True),
        'reg_alpha': trial.suggest_float('xgb__reg_alpha', 1e-5, 10.0, log=True),
        'reg_lambda': trial.suggest_float('xgb__reg_lambda', 1e-5, 10.0, log=True),
        'objective': 'binary:logistic',
        'eval_metric': 'auc', # Tracks AUC optimization
        'random_state': random_state
    }

    # Adjust selector percentile to prevent all features got selected
    selector_percentile = trial.suggest_int('selector__percentile', 10, 70, step=5)

    current_selector = SelectPercentile(
        score_func=f_classif,
        percentile=selector_percentile
    )

    current_xgb_model = XGBClassifier(**xgb_params)

    cv_scores = []
    fold_selected_features = []
    feature_names = np.array(X_train_df.columns)

    for train_inner_idx, val_inner_idx in inner_cv.split(X_train_df, y_train_series):
        X_train_inner_fold = X_train_df.iloc[train_inner_idx]
        X_val_inner_fold = X_train_df.iloc[val_inner_idx]
        y_train_inner_fold = y_train_series.iloc[train_inner_idx]
        y_val_inner_fold = y_train_series.iloc[val_inner_idx]

        # Feature selection on training fold only
        current_selector.fit(X_train_inner_fold, y_train_inner_fold)
        X_train_selected = current_selector.transform(X_train_inner_fold)
        X_val_selected = current_selector.transform(X_val_inner_fold)

        selected_mask = current_selector.get_support()
        fold_selected_features.append(feature_names[selected_mask].tolist())

        # Train XGBoost on selected features
        current_xgb_model.fit(
            X_train_selected,
            y_train_inner_fold,
            eval_set=[(X_val_selected, y_val_inner_fold)],
            verbose=False
        )

        # Evaluate on validation fold
        y_pred_proba = current_xgb_model.predict_proba(X_val_selected)[:, 1]
        fold_score = roc_auc_score(y_val_inner_fold, y_pred_proba)
        cv_scores.append(fold_score)

    mean_cv_score = np.mean(cv_scores)
    std_cv_score = np.std(cv_scores)

    # Log the number of features selected across folds
    trial.set_user_attr('num_features_selected',
                        int(np.mean([len(f) for f in fold_selected_features])))
    trial.set_user_attr('std_cv_score', std_cv_score)

    return mean_cv_score

"""### 6.2 XGBoost Pipeline function"""

def run_xgb_external_cv(
    datasets,
    inner_cv_type='3fold',
    scoring='roc_auc',
    random_state=42,
    n_trials=50
):
    outer_results = []
    n_datasets = len(datasets)

    for test_idx in range(n_datasets):
        print(f"\nExternal test dataset: Dataset {test_idx + 1}")
        print("-" * 50)

        # STEP 0: CREATE a N-1 TRAINING POOL AND HELD-OUT EXTERNAL TEST DATASET
        train_sets = [datasets[i] for i in range(n_datasets) if i != test_idx]

        # Assume all X_clean dataframes have the same column order and names
        feature_names_orig = datasets[0][0].columns.tolist()

        X_train = np.vstack([d[0].to_numpy() for d in train_sets])
        y_train = np.concatenate([np.asarray(d[1]) for d in train_sets])

        X_test, y_test = datasets[test_idx]
        X_test = X_test.to_numpy()
        y_test = np.asarray(y_test)

        print(f"Training set shape (n-1 global pool): {X_train.shape}")
        print(f"Test set shape (n=1 hold-out evaluation dataset): {X_test.shape}")

        # INNER CV SETUP
        if inner_cv_type == '2fold':
            inner_cv = StratifiedKFold(n_splits=2, shuffle=True, random_state=random_state)
        elif inner_cv_type == '3fold':
            inner_cv = StratifiedKFold(n_splits=3, shuffle=True, random_state=random_state)
        elif inner_cv_type == '5fold':
            inner_cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=random_state)
        elif inner_cv_type == 'loocv':
            inner_cv = LeaveOneOut()
        else:
            raise ValueError("inner_cv_type must be '2fold', '3fold', '5fold', or 'loocv'")

        # CONVERT TO DATAFRAMES FOR FEATURE TRACKING (Preserving original names)
        X_train_df = pd.DataFrame(X_train, columns=feature_names_orig)
        y_train_series = pd.Series(y_train)
        X_test_df = pd.DataFrame(X_test, columns=feature_names_orig)

        # BASIC NAN / INF CHECKS
        for name, df in [("X_train_df", X_train_df), ("X_test_df", X_test_df)]:
            nans = df.isna().sum().sum()
            infs = np.isinf(df.to_numpy()).sum()
            if nans > 0 or infs > 0:
                raise ValueError(f"NaNs/Infs detected in {name}: NaNs={nans}, Infs={infs}")

        if np.isnan(y_train_series).any() or np.isinf(y_train_series).any():
            raise ValueError("NaNs or Infs detected in y_train_series.")

        # STEP 1: HYPERPARAMETER TUNING WITH OPTUNA
        print(f"\nExecuting Optuna optimization for {n_trials} trials across internal {inner_cv_type} loops...")

        optuna.logging.set_verbosity(optuna.logging.WARNING) # Clean up OPTUNA warning statements
        study = optuna.create_study(direction='maximize', sampler=optuna.samplers.TPESampler(seed=random_state))

        func = lambda trial: objective(trial, X_train_df, y_train_series, inner_cv, scoring, random_state)
        study.optimize(func, n_trials=n_trials, show_progress_bar=True)

        best_trial = study.best_trial
        best_pipeline_params = best_trial.params
        best_inner_cv_score = best_trial.value


        best_selector_params = {k.replace('selector__', ''): v for k, v in best_pipeline_params.items() if k.startswith('selector__')}
        best_xgb_params = {k.replace('xgb__', ''): v for k, v in best_pipeline_params.items() if k.startswith('xgb__')}

        best_xgb_params.update({
            'objective': 'binary:logistic',
            'eval_metric': 'logloss',
            'grow_policy': 'lossguide',
            'random_state': random_state
        })

        # STEP 2: EXTRACT THE UNION OF SELECTED FEATURES FROM THE BEST TRIAL
        union_selected_features = best_trial.user_attrs.get("union_features", feature_names_orig)
        n_selected_features = len(union_selected_features)

        print(f"\nFeature selection complete via Internal CV Fold Union.")
        print(f"Retained {n_selected_features} out of {len(feature_names_orig)} features.")

        # STEP 3: MANUAL FINAL REFIT ON ALL N-1 DATA USING ONLY UNION OF SELECTED FEATURES
        # X_train_final and X_test_final are filtered by union_selected_features here
        X_train_final = X_train_df[union_selected_features]
        X_test_final = X_test_df[union_selected_features]

        print("Retraining final XGBoost model on filtered n-1 training data...")

        # The final model of the XGBClassifier with selected features and hyperparameters
        final_model = XGBClassifier(**best_xgb_params)

        final_model.fit(X_train_final, y_train_series)

        # STEP 4: EXTERNAL HELD-OUT DATASET EVALUATION
        print("Evaluating final model on isolated held-out dataset...")

        y_pred = final_model.predict(X_test_final)

        is_binary = len(np.unique(y_train)) == 2
        f1_avg = 'binary' if is_binary else 'macro'

        accuracy = accuracy_score(y_test, y_pred)
        balanced_acc = balanced_accuracy_score(y_test, y_pred)
        f1 = f1_score(y_test, y_pred, average=f1_avg)

        external_auc = None
        y_prob = None

        if is_binary:
            try:
                y_prob = final_model.predict_proba(X_test_final)[:, 1]
                external_auc = roc_auc_score(y_test, y_prob)
            except Exception as e:
                print(f"Warning: Could not compute external AUC: {e}")

        result = {
            'held_out_dataset': test_idx + 1,
            'inner_cv_type': inner_cv_type,
            'best_params': best_pipeline_params,
            'best_inner_cv_score': best_inner_cv_score,
            'selected_features_list': union_selected_features, # With actual feature names
            'n_features_used': n_selected_features,
            'external_accuracy': accuracy,
            'external_balanced_accuracy': balanced_acc,
            'external_f1': f1,
            'external_auc': external_auc,
            'confusion_matrix': confusion_matrix(y_test, y_pred),
            'y_test': y_test,
            'y_pred': y_pred,
            'y_prob': y_prob
        }
        outer_results.append(result)

    return outer_results

